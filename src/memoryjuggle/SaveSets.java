private void refreshList(ArrayList<CardSet> sets) {
    listModel.clear();
    shownSets.clear();
    for (CardSet set : sets) {
        listModel.addElement(set.getName());
        shownSets.add(set);
    }
}
 public CardSet getSelectedSet(){
    int i = listSets.getSelectedIndex();
     if(i == -1 ) {
       JOptionPane.showMessageDialog(this, "Select a set first.");
       return null;
     }
     else{
         return shownSets.get(i);
     }
}
