public class CardPair {
    private String cardA;
    private String cardB;
    CardPair(String a, String b) {
        cardA = a;
        cardB = b;
    }
    public String getCardA() {
        return cardA;
    }
    public String getCardB() {
        return cardB;
    }
    
}
