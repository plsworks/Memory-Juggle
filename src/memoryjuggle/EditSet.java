    private void refreshTable() {
    tableModel.setRowCount(0);
    if (currentSet == null) {
        return;
    } 
    for (CardPair pair : currentSet.getPairs()) {
            tableModel.addRow(new Object[]{
                    pair.getCardA(),
                    pair.getCardB()
            });
        }
    }
  
    
